#!/usr/bin/env python3
"""Train only the local-passage SAC on captured frozen-reaching states."""
from __future__ import annotations

import argparse
from collections import deque
import copy
import csv
import hashlib
import json
from pathlib import Path
import sys
import time

ROOT = Path(__file__).resolve().parents[2]
sys.path[:0] = [str(ROOT), str(ROOT / "src")]

import numpy as np
import torch

from rl_risk_sac.algorithms.dual_sac import build_thesis_sac
from rl_risk_sac.algorithms.local_replay import LocalReplayBuffer
from rl_risk_sac.envs.local_avoidance_env import LocalAvoidanceEnv
from rl_risk_sac.tasks.local_avoidance import (
    PROTOCOL, LOCAL_OBSERVATION_DIM, actor_digest, contract_digest, validate_local_config,
    local_protocol, geometric_mode,
)
from rl_risk_sac.tasks.local_samples import validate_bank
from rl_risk_sac.utils.config import load_config
from rl_risk_sac.utils.local_training import local_training_schedule, sac_resume_contract, schedule_migrations
from rl_risk_sac.utils.training_logs import CsvLog, detailed_log_enabled, format_training_progress
from scripts.core.train_thesis_homotopy import (
    accrue_update_credit, apply_stage_profile, initialize_frozen_reaching, load_reference_actor,
)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", default="configs/experiments/paper_local_avoidance_geometry.yaml")
    parser.add_argument("--bank", required=True, help="training start-state bank generated by the frozen S0 policy")
    parser.add_argument("--initialize-reaching-from")
    parser.add_argument("--initialize-actor-from", help="optional old avoidance Actor; context columns start at zero")
    parser.add_argument("--resume", help="complete local-passage checkpoint, never global-reaching replay")
    parser.add_argument("--steps", type=int, default=1000000, help="additional environment steps (default: 1000k)")
    parser.add_argument("--save-interval", type=int, default=5000)
    parser.add_argument("--run-name", required=True)
    parser.add_argument("--output-dir", default="outputs/local_avoidance")
    parser.add_argument("--device", choices=("cpu", "cuda:auto"))
    parser.add_argument("--num-envs", type=int, help="parallel simulators; formal default: train.num_envs (8); 1 keeps serial execution")
    parser.add_argument("--validation-mode", action="store_true")
    args = parser.parse_args()
    if min(args.steps, args.save_interval) < 1:
        parser.error("steps and save interval must be positive")
    if args.num_envs is not None and args.num_envs < 1:
        parser.error("num-envs must be positive")
    if args.resume and (args.initialize_reaching_from or args.initialize_actor_from):
        parser.error("resume restores both SACs; initialization flags are incompatible")
    if not args.resume and not args.initialize_reaching_from:
        parser.error("a fresh run requires --initialize-reaching-from")
    config = load_config(args.config)
    apply_stage_profile(config, "s1")
    validate_local_config(config)
    if args.device:
        config["device"] = args.device
    progress_interval = int(config["train"].get("progress_interval", 1000))
    update_log_interval = int(config["train"].get("update_log_interval", 10))
    if min(progress_interval, update_log_interval) < 1:
        parser.error("progress_interval and update_log_interval must be positive")
    schedule = local_training_schedule(config, validation_mode=args.validation_mode)
    torch.set_num_threads(6)
    seed = int(config["seed"])
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)
    rng = np.random.default_rng(seed)
    agent = build_thesis_sac(LOCAL_OBSERVATION_DIM, 6, config)
    local = config["local_avoidance"]
    capacity = min(512, local["replay_capacity"]) if args.validation_mode else local["replay_capacity"]
    batch_size = schedule["batch_size"]
    update_after = schedule["update_after"]
    warmup = schedule["warmup_steps"]
    replay = LocalReplayBuffer(capacity, agent.device, seed + 1, protocol=local_protocol(config))
    counters = dict(steps=0, episodes=0, updates=0, update_credit=0.)
    loaded = None
    if args.resume:
        # Worker RNG tensors must remain on CPU when sent through spawn pipes.
        # Each SAC's loader moves its own networks/optimizer state to its device.
        loaded = torch.load(args.resume, map_location="cpu", weights_only=False)
        if loaded.get("protocol") != local_protocol(config):
            raise ValueError("local resume task protocol differs; regenerate bank and start fresh, never reuse old replay")
        if (loaded["contract_sha256"] != contract_digest(config)
                or sac_resume_contract(loaded["config"]) != sac_resume_contract(config)):
            raise ValueError("local task/SAC contract differs; do not resume old replay")
        if loaded["validation_mode"] != args.validation_mode:
            raise ValueError("validation checkpoints cannot resume formal training")
        agent.load_state_dict(loaded["agent"])
        replay.load_state_dict(loaded["replay"])
        counters.update(loaded["counters"])
        rng.bit_generator.state = loaded["rng"]
        torch.set_rng_state(loaded["torch_rng"].cpu())
        if torch.cuda.is_available() and loaded["cuda_rng"] is not None:
            torch.cuda.set_rng_state_all([value.cpu() for value in loaded["cuda_rng"]])
        reaching_initialization = loaded["reaching_initialization"]
    else:
        reaching_initialization = initialize_frozen_reaching(agent, Path(args.initialize_reaching_from))
        if args.initialize_actor_from:
            reference = load_reference_actor(agent.avoidance, Path(args.initialize_actor_from), policy="avoidance")
            if geometric_mode(config):
                # Context shape is unchanged but now describes a different task.
                with torch.no_grad():
                    reference.backbone[0].weight[:, 241:].zero_()
            agent.avoidance.actor.load_state_dict(reference.state_dict())
            agent.avoidance.reset_chain_reference_actor()
    bank = torch.load(args.bank, map_location="cpu", weights_only=False)
    # Fresh formal runs must use filtered starts. Historical resumes retain
    # their exact bank/replay; evaluation also permits old banks for comparison.
    bank_ids = sorted(validate_bank(bank, config, agent.reaching, split=("train",),
                                   require_path_verification=not args.resume and not args.validation_mode))
    verified_samples = sum("path_verification" in sample for sample in bank["samples"])
    print(f"whole-arm path witnesses: {verified_samples}/{len(bank_ids)} training starts", flush=True)
    bank_fingerprint = hashlib.sha256(json.dumps(bank_ids).encode()).hexdigest()
    if loaded and loaded["bank_fingerprint"] != bank_fingerprint:
        raise ValueError("local resume requires the same training bank")
    migrations = schedule_migrations(loaded, schedule)
    saved_num_envs = loaded.get("parallel_num_envs") if loaded else None
    num_envs = (args.num_envs if args.num_envs is not None else
                saved_num_envs if saved_num_envs is not None else
                1 if args.validation_mode else int(config["train"].get("num_envs", 8)))
    if num_envs < 1:
        raise ValueError("train.num_envs must be positive")
    if loaded and "parallel_workers" in loaded and num_envs != saved_num_envs:
        raise ValueError(f"parallel checkpoint uses {saved_num_envs} environments, requested {num_envs}; "
                         "keep the worker count to preserve active episodes")
    frozen_digest = actor_digest(agent.reaching.actor)
    output = Path(args.output_dir) / args.run_name
    output.mkdir(parents=True, exist_ok=False)
    checkpoints = output / "checkpoints"
    checkpoints.mkdir()
    manifest = dict(protocol=local_protocol(config), config=config, training_policy="avoidance",
                    bank=str(Path(args.bank).resolve()), bank_fingerprint=bank_fingerprint,
                    bank_samples=len(bank_ids), source="frozen_s0_policy",
                    path_verified_samples=verified_samples,
                    reaching_initialization=reaching_initialization,
                    initialize_actor_from=args.initialize_actor_from,
                    resume=args.resume, validation_mode=args.validation_mode,
                    num_envs=num_envs,
                    training_schedule=schedule, training_schedule_migrations=migrations,
                    execution=dict(mode="spawn_pipeline" if num_envs > 1 else "serial",
                                   max_policy_lag_transitions=num_envs if num_envs > 1 else 0,
                                   recovery_actor_device="cpu" if num_envs > 1 else str(agent.device),
                                   checkpoint_flushes_deferred_updates=True),
                    observation_dim=LOCAL_OBSERVATION_DIM,
                    reward_definition="local passage progress/risk/time/success; no final pose reward",
                    replay_shared_with_global_task=False, automatic_switching=False)
    (output / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n")
    print(f"local SAC: batch={batch_size}, updates/transition={schedule['updates_per_transition']:g}, "
          f"diagnostics_every={schedule['diagnostic_interval']} updates", flush=True)
    if migrations and migrations[-1]["step"] == counters["steps"]:
        print(f"migrating local training schedule at step={counters['steps']}", flush=True)
    if num_envs > 1:
        from scripts.core.train_parallel_local_avoidance import run_parallel_local
        run_parallel_local(args=args, config=config, agent=agent, replay=replay, bank=bank,
                           bank_ids=bank_ids, bank_fingerprint=bank_fingerprint, rng=rng,
                           counters=counters, loaded=loaded, num_envs=num_envs, output=output,
                           checkpoints=checkpoints, reaching_initialization=reaching_initialization,
                           frozen_digest=frozen_digest, batch_size=batch_size,
                           update_after=update_after, warmup=warmup, schedule=schedule,
                           migrations=migrations)
        return
    env = LocalAvoidanceEnv(config, agent.reaching)
    active, observation = False, None
    episode_return = 0.
    episode_steps = 0
    episode_external = episode_self = float("inf")
    if loaded:
        observation = env.load_state_dict(loaded["environment"])
        active = not env.finished
        episode_return, episode_steps = loaded["episode_return"], loaded["episode_steps"]
        episode_external, episode_self = loaded["episode_external"], loaded["episode_self"]
    budget_end = counters["steps"] + args.steps
    start_steps = counters["steps"]
    started = time.perf_counter()
    recent_successes = deque(loaded.get("recent_successes", []) if loaded else [], maxlen=100)
    last_update = {}
    print(format_training_progress(counters["steps"], budget_end, 0., recent_successes,
                                   label="越障训练", completed_steps=0), flush=True)

    def save():
        if actor_digest(agent.reaching.actor) != frozen_digest:
            raise RuntimeError("frozen reaching actor changed during avoidance training")
        torch.save(dict(
            protocol=local_protocol(config), config=config, contract_sha256=contract_digest(config),
            agent=agent.state_dict(), replay=replay.state_dict(), counters=dict(counters),
            rng=rng.bit_generator.state, torch_rng=torch.get_rng_state(),
            cuda_rng=torch.cuda.get_rng_state_all() if torch.cuda.is_available() else None,
            environment=env.state_dict(), episode_return=episode_return, episode_steps=episode_steps,
            episode_external=episode_external, episode_self=episode_self,
            bank_fingerprint=bank_fingerprint, train_sample_ids=bank_ids,
            train_trace_seeds=sorted({sample["provenance"]["seed"] for sample in bank["samples"]}),
            reaching_initialization=reaching_initialization, validation_mode=args.validation_mode,
            recent_successes=list(recent_successes),
            parallel_num_envs=1,
            training_schedule=schedule, training_schedule_migrations=migrations,
        ), checkpoints / f"step_{counters['steps']:07d}.pt")
        agent.avoidance.save_actor(checkpoints / f"avoidance_actor_step_{counters['steps']:07d}.pt")

    fields = ("steps", "episode", "sample_id", "length", "return", "local_success", "local_failure",
              "timeout", "local_progress", "min_external_mesh_distance_m", "min_self_mesh_distance_m")
    progress_fields = ("steps", "episodes", "updates", "update_credit", "replay_size", "elapsed_s", "steps_per_second",
                       "remaining_steps", "eta_seconds", "recent_episodes", "recent_success_rate",
                       "critic_loss", *agent.avoidance.last_actor_metrics,
                       "alpha", "q1_mean", "q2_mean", "target_mean", "critic_gradient_norm",
                       "actor_gradient_norm", "actor_updated")
    try:
        with (output / "episodes.csv").open("w", newline="") as handle, \
                CsvLog(output / "updates.csv", enabled=detailed_log_enabled(config, "updates")) as updates_log, \
                CsvLog(output / "progress.csv", progress_fields) as progress_log:
            writer = csv.DictWriter(handle, fieldnames=fields)
            writer.writeheader()
            progress_log.writeheader()
            while counters["steps"] < budget_end:
                if not active:
                    sample = bank["samples"][int(rng.integers(len(bank["samples"]))) ]
                    observation, _ = env.reset(options={"sample": sample})
                    active, episode_return, episode_steps = True, 0., 0
                    episode_external = episode_self = float("inf")
                action = (rng.uniform(-1., 1., 6).astype(np.float32)
                          if counters["steps"] < warmup else agent.select_action(observation))
                next_observation, reward, terminated, truncated, info = env.step(action)
                # This is a finite-horizon subtask; remaining time is observable.
                replay.add(observation, action, reward, next_observation, terminated or truncated)
                counters["steps"] += 1
                episode_steps += 1
                episode_return += reward
                episode_external = min(episode_external, info["min_external_mesh_distance_m"])
                episode_self = min(episode_self, info["min_self_mesh_distance_m"])
                observation = next_observation
                if replay.size >= max(batch_size, update_after):
                    due = accrue_update_credit(counters, schedule["updates_per_transition"])
                    for _ in range(due):
                        sample_batch = replay.sample(batch_size)
                        next_update = counters["updates"] + 1
                        collect = next_update == 1 or next_update % schedule["diagnostic_interval"] == 0
                        metrics = agent.update(sample_batch, reference_observations=sample_batch,
                                               collect_diagnostics=collect, check_finite=True)
                        counters["updates"] += 1
                        if not all(np.isfinite(value) for value in metrics.values()):
                            raise RuntimeError("nonfinite local SAC update")
                        if collect:
                            last_update = metrics
                            updates_log.writerow({"steps": counters["steps"], **metrics})
                if terminated or truncated:
                    counters["episodes"] += 1
                    recent_successes.append(bool(info["local_success"]))
                    writer.writerow(dict(steps=counters["steps"], episode=counters["episodes"],
                                         sample_id=info["sample_id"], length=episode_steps,
                                         **{"return": episode_return},
                                         **{key: info[key] for key in ("local_success", "local_failure", "timeout", "local_progress")},
                                         min_external_mesh_distance_m=episode_external,
                                         min_self_mesh_distance_m=episode_self))
                    handle.flush()
                    active = False
                if counters["steps"] % progress_interval == 0 or counters["steps"] == budget_end:
                    elapsed = max(time.perf_counter() - started, 1e-9)
                    speed = (counters["steps"] - start_steps) / elapsed
                    rate = float(np.mean(recent_successes)) if recent_successes else ""
                    remaining = budget_end - counters["steps"]
                    progress_log.writerow(dict(**counters, replay_size=replay.size, elapsed_s=elapsed,
                                               steps_per_second=speed, remaining_steps=remaining,
                                               eta_seconds=remaining / speed,
                                               recent_episodes=len(recent_successes),
                                               recent_success_rate=rate, **last_update))
                    progress_log.flush()
                    updates_log.flush()
                    print(format_training_progress(counters["steps"], budget_end, elapsed, recent_successes,
                                                   label="越障训练", completed_steps=counters["steps"] - start_steps)
                          + f" | 回合={counters['episodes']} 更新={counters['updates']}", flush=True)
                if counters["steps"] % args.save_interval == 0:
                    save()
                    print(f"saved local checkpoint step={counters['steps']}", flush=True)
            if counters["steps"] % args.save_interval:
                save()
    finally:
        env.close()
    (output / "summary.json").write_text(json.dumps({**counters, "replay_size": replay.size,
                "frozen_reaching_actor_unchanged": actor_digest(agent.reaching.actor) == frozen_digest,
                "validation_mode": args.validation_mode, "num_envs": 1,
                "training_schedule": schedule}, indent=2) + "\n")
    print(f"saved {output}", flush=True)


if __name__ == "__main__":
    main()
